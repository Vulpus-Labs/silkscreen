#[test]
fn faceplate_excludes_controls_layer() {
    let dir = out_dir("excludes_controls");
    let path = write_svg(
        &dir,
        "panel.svg",
        &svg(
            r##"<g id="controls"><rect id="knob.gain" x="0" y="0" width="200" height="100" fill="#ff00ff"/></g>"##,
        ),
    );
    let generated = Faceplate::new(&path)
        .scales(&[1.0, 2.0])
        .out_dir(&dir)
        .generate()
        .unwrap();
    assert!(!generated.analysis.faceplate_svg.contains("knob.gain"));
    for (scale, png) in &generated.pngs {
        let pixmap = Pixmap::load_png(png).unwrap();
        let (w, h) = Size::new(200.0, 100.0).to_physical(*scale);
        assert_eq!((pixmap.width(), pixmap.height()), (w, h));
        let magenta = pixmap
            .pixels()
            .iter()
            .filter(|p| p.red() > 200 && p.blue() > 200 && p.green() < 50)
            .count();
        assert_eq!(magenta, 0, "controls layer leaked into the {scale}x render");
    }
}

#[test]
fn generates_layout_module() {
    let dir = out_dir("codegen");
    let path = write_svg(
        &dir,
        "panel.svg",
        &svg(r##"<g id="controls">
               <rect id="knob.gain" x="10" y="20" width="30" height="40" fill="#f0f"/>
               <rect id="knob.pan" x="100" y="20" width="30" height="40" fill="#f0f"/>
             </g>"##),
    );
    let fp = Faceplate::new(&path).scales(&[1.0, 1.5]).out_dir(&dir);
    let generated = fp.generate().unwrap();
    let code = std::fs::read_to_string(&generated.code).unwrap();
    assert_eq!(generated.code, dir.join("panel.rs"));
    assert!(code.starts_with("// @generated by silkscreen-build from panel.svg."));
    for needle in [
        "pub const SIZE: ::silkscreen::core::Size = ::silkscreen::core::Size::new(200.0, 100.0);",
        "pub const GAIN: ::silkscreen::core::ControlId = ::silkscreen::core::ControlId(0);",
        "pub const PAN: ::silkscreen::core::ControlId = ::silkscreen::core::ControlId(1);",
        "::silkscreen::core::ControlSpec::new(ids::GAIN, \"gain\", ::silkscreen::core::ControlKind::Knob, ::silkscreen::core::Rect::new(10.0, 20.0, 30.0, 40.0)),",
        "pub static LAYOUT: ::silkscreen::core::Layout",
        "pub static FACEPLATE: ::silkscreen::core::EmbeddedPngs",
        "panel@1.5x.png",
        "pub struct Controls<B> {\n    pub gain: B,\n    pub pan: B,\n}",
        "pub fn into_array(self) -> [B; 2] {\n        [self.gain, self.pan]",
    ] {
        assert!(code.contains(needle), "missing:\n{needle}\n\nin:\n{code}");
    }

    // Deterministic: generating again changes nothing.
    fp.generate().unwrap();
    assert_eq!(std::fs::read_to_string(&generated.code).unwrap(), code);

    let custom = Faceplate::new(&path)
        .scales(&[1.0])
        .core_path("::silkscreen_core")
        .out_dir(&dir)
        .generate()
        .unwrap();
    let code = std::fs::read_to_string(custom.code).unwrap();
    assert!(code.contains("pub const SIZE: ::silkscreen_core::Size"));
}

