/// A 64×64 PNG: transparent, with an opaque green disc in the middle.
fn write_png_frame(dir: &std::path::Path, name: &str) -> PathBuf {
    let mut p = Pixmap::new(64, 64).unwrap();
    let mut paint = resvg::tiny_skia::Paint::default();
    paint.set_color_rgba8(0, 255, 0, 255);
    let disc = resvg::tiny_skia::PathBuilder::from_circle(32.0, 32.0, 20.0).unwrap();
    p.fill_path(
        &disc,
        &paint,
        resvg::tiny_skia::FillRule::Winding,
        resvg::tiny_skia::Transform::identity(),
        None,
    );
    let path = dir.join(name);
    p.save_png(&path).unwrap();
    path
}

