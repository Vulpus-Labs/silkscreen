use std::path::PathBuf;

use resvg::tiny_skia::Pixmap;
use silkscreen_build::{BuildError, Faceplate};
use silkscreen_core::{ControlKind, Rect, Size};

fn svg(body: &str) -> String {
    format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape" width="200" height="100">
  <rect width="200" height="100" fill="#202020"/>
  {body}
</svg>"##
    )
}

fn analyze(text: &str) -> Result<silkscreen_build::Analysis, BuildError> {
    Faceplate::new("test.svg").analyze_str(text)
}

fn err(text: &str) -> String {
    analyze(text).unwrap_err().to_string()
}

fn out_dir(name: &str) -> PathBuf {
    let dir = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

fn write_svg(dir: &std::path::Path, name: &str, text: &str) -> PathBuf {
    let path = dir.join(name);
    std::fs::write(&path, text).unwrap();
    path
}

#[test]
fn finds_controls_by_id_or_inkscape_label() {
    let by_id = analyze(&svg(
        r##"<g id="controls"><rect id="knob.gain" x="10" y="20" width="30" height="40" fill="#f0f"/></g>"##,
    ))
    .unwrap();
    assert_eq!(by_id.size, Size::new(200.0, 100.0));
    assert_eq!(by_id.controls.len(), 1);
    assert_eq!(by_id.controls[0].name, "gain");
    assert_eq!(by_id.controls[0].kind, ControlKind::Knob);
    assert_eq!(by_id.controls[0].rect, Rect::new(10.0, 20.0, 30.0, 40.0));

    let by_label = analyze(&svg(
        r##"<g id="layer2" inkscape:groupmode="layer" inkscape:label="controls"><circle id="knob.pan" cx="50" cy="50" r="10" fill="#f0f"/></g>"##,
    ))
    .unwrap();
    assert_eq!(by_label.controls[0].rect, Rect::new(40.0, 40.0, 20.0, 20.0));
}

#[test]
fn rects_are_absolute_through_transforms() {
    let a = analyze(&svg(
        r##"<g transform="translate(5,5)"><g id="controls" transform="translate(10,20) scale(2)">
             <rect id="knob.a" x="5" y="5" width="10" height="10" fill="#f0f"/>
             <g id="knob.b" transform="translate(50,0)"><rect width="4" height="6" fill="#f0f"/></g>
           </g></g>"##,
    ))
    .unwrap();
    // 5 + 10 + 2*5 = 25; 5 + 20 + 2*5 = 35; size 2*10.
    assert_eq!(a.controls[0].rect, Rect::new(25.0, 35.0, 20.0, 20.0));
    // Group markers work too: 5 + 10 + 2*50 = 115.
    assert_eq!(a.controls[1].rect, Rect::new(115.0, 25.0, 8.0, 12.0));
}

