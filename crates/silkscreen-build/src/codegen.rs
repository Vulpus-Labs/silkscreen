//! Rust source generation for a faceplate's layout.

use std::fmt::Write as _;
use std::path::Path;

use silkscreen_core::{ControlKind, Size};

use crate::Control;

#[derive(Clone)]
pub(crate) enum PngRef {
    /// A file name inside `$OUT_DIR`.
    OutDir(String),
    Absolute(String),
    /// Fetch mode: a URL the web host fetches at run time.
    Url(String),
}

/// One skin's frames, each its logical size and `(scale, png)` pairs.
pub(crate) struct SkinCode {
    pub name: String,
    pub frames: Vec<(Size, Vec<(f32, PngRef)>)>,
    pub sweep_deg: Option<f32>,
    pub cycle_deg: Option<f32>,
}

pub(crate) struct Input<'a> {
    pub source: &'a Path,
    pub core: &'a str,
    pub size: Size,
    pub controls: &'a [Control],
    pub pngs: &'a [(f32, PngRef)],
    pub skins: &'a [SkinCode],
    pub pages: &'a [PageGroupCode],
}

/// A page group's region and each page's faceplate PNGs.
pub(crate) struct PageGroupCode {
    pub name: String,
    pub region: silkscreen_core::Rect,
    pub pages: Vec<Vec<(f32, PngRef)>>,
}

/// Generate the module. Output depends only on the input, so the same SVG
/// always yields byte-identical code.
#[allow(clippy::too_many_lines)] // linear template; splitting it hurts readability
pub(crate) fn generate(input: &Input) -> String {
    let Input {
        source,
        core,
        size,
        controls,
        pngs,
        skins,
        pages,
    } = input;
    let file = source
        .file_name()
        .map_or_else(String::new, |f| f.to_string_lossy().into_owned());
    let n = controls.len();
    let mut s = String::new();

    let _ = writeln!(
        s,
        "// @generated by silkscreen-build from {file}. Do not edit."
    );
    s.push('\n');
    let _ = writeln!(s, "/// Logical size of the faceplate.");
    let _ = writeln!(
        s,
        "pub const SIZE: {core}::Size = {core}::Size::new({:?}, {:?});",
        size.w, size.h
    );
    s.push('\n');

    let _ = writeln!(
        s,
        "/// One [`ControlId`]({core}::ControlId) per control in the SVG's controls layer."
    );
    let _ = writeln!(s, "pub mod ids {{");
    for (i, c) in controls.iter().enumerate() {
        let _ = writeln!(
            s,
            "    pub const {}: {core}::ControlId = {core}::ControlId({i});",
            c.name.to_ascii_uppercase()
        );
    }
    let _ = writeln!(s, "}}");
    s.push('\n');

    let mut groups: Vec<(&str, Vec<(u16, &str)>)> = Vec::new();
    for c in *controls {
        if let ControlKind::Radio { group, position } = c.kind {
            match groups.iter_mut().find(|(g, _)| *g == group) {
                Some((_, buttons)) => buttons.push((position, &c.name)),
                None => groups.push((group, vec![(position, &c.name)])),
            }
        }
    }
    if !groups.is_empty() {
        let _ = writeln!(
            s,
            "/// Each radio group's buttons, in position order. A group's buttons"
        );
        let _ = writeln!(s, "/// share one stepped param.");
        let _ = writeln!(s, "pub mod radios {{");
        for (group, mut buttons) in groups {
            buttons.sort_unstable();
            let ids: Vec<String> = buttons
                .iter()
                .map(|(_, name)| format!("super::ids::{}", name.to_ascii_uppercase()))
                .collect();
            let _ = writeln!(
                s,
                "    pub const {}: [{core}::ControlId; {}] = [{}];",
                group.to_ascii_uppercase(),
                ids.len(),
                ids.join(", ")
            );
        }
        let _ = writeln!(s, "}}");
        s.push('\n');
    }

    if !skins.is_empty() {
        let _ = writeln!(
            s,
            "/// Sprite frames for the controls that name them in `data-skin`."
        );
        // Sizes such as a fader cap's are computed, e.g. 14.400001.
        let _ = writeln!(s, "#[allow(clippy::unreadable_literal)]");
        let _ = writeln!(s, "pub mod skins {{");
        for skin in *skins {
            let _ = writeln!(
                s,
                "    pub static {}: {core}::Skin = {core}::Skin::new({:?}, &[",
                skin.name.to_ascii_uppercase(),
                skin.name
            );
            for (size, frame) in &skin.frames {
                let _ = writeln!(
                    s,
                    "        {core}::EmbeddedPngs::{}({core}::Size::new({:?}, {:?}), &[",
                    constructor(frame),
                    size.w,
                    size.h
                );
                for (scale, png) in frame {
                    let _ = writeln!(s, "            ({scale:?}, {}),", include(png));
                }
                let _ = writeln!(s, "        ]),");
            }
            let sweep = skin
                .sweep_deg
                .map(|deg| format!(".with_sweep({deg:?})"))
                .unwrap_or_default();
            let cycle = skin
                .cycle_deg
                .map(|deg| format!(".with_cycle({deg:?})"))
                .unwrap_or_default();
            let _ = writeln!(s, "    ]){sweep}{cycle};");
        }
        let _ = writeln!(s, "}}");
        s.push('\n');
    }

    // Marker rects may be fractional, e.g. 124.520004.
    let _ = writeln!(s, "#[allow(clippy::unreadable_literal)]");
    let _ = writeln!(s, "pub static CONTROLS: [{core}::ControlSpec; {n}] = [");
    for c in *controls {
        let r = c.rect;
        let mut skin = c
            .skin
            .as_ref()
            .map(|k| format!(".with_skin(&skins::{})", k.to_ascii_uppercase()))
            .unwrap_or_default();
        if let Some((group, page)) = &c.page {
            let g = input
                .pages
                .iter()
                .position(|p| p.name == *group)
                .expect("a control's page group was found by the analysis");
            let _ = write!(skin, ".on_page({g}, {page})");
        }
        let _ = writeln!(
            s,
            "    {core}::ControlSpec::new(ids::{}, {:?}, {core}::ControlKind::{:?}, {core}::Rect::new({:?}, {:?}, {:?}, {:?})){skin},",
            c.name.to_ascii_uppercase(),
            c.name,
            c.kind,
            r.x,
            r.y,
            r.w,
            r.h
        );
    }
    let _ = writeln!(s, "];");
    s.push('\n');

    if pages.is_empty() {
        let _ = writeln!(
            s,
            "pub static LAYOUT: {core}::Layout = {core}::Layout::new(SIZE, &CONTROLS);"
        );
    } else {
        let _ = writeln!(
            s,
            "pub static LAYOUT: {core}::Layout = {core}::Layout::new(SIZE, &CONTROLS).with_pages(&PAGES);"
        );
        s.push('\n');
        let _ = writeln!(
            s,
            "/// Each page group's index in [`LAYOUT`]'s pages (design/faceplates.md)."
        );
        let _ = writeln!(s, "pub mod page_groups {{");
        for (i, g) in pages.iter().enumerate() {
            let _ = writeln!(
                s,
                "    pub const {}: u16 = {i};",
                g.name.to_ascii_uppercase()
            );
        }
        let _ = writeln!(s, "}}");
        s.push('\n');
        let _ = writeln!(s, "/// Each page group's tabs, in page order.");
        let _ = writeln!(s, "pub mod tabs {{");
        for g in *pages {
            let mut tabs: Vec<(u16, &str)> = controls
                .iter()
                .filter_map(|c| match c.kind {
                    ControlKind::Tab { group, position } if group == g.name => {
                        Some((position, c.name.as_str()))
                    }
                    _ => None,
                })
                .collect();
            tabs.sort_unstable();
            let ids: Vec<String> = tabs
                .iter()
                .map(|(_, name)| format!("super::ids::{}", name.to_ascii_uppercase()))
                .collect();
            let _ = writeln!(
                s,
                "    pub const {}: [{core}::ControlId; {}] = [{}];",
                g.name.to_ascii_uppercase(),
                ids.len(),
                ids.join(", ")
            );
        }
        let _ = writeln!(s, "}}");
        s.push('\n');
        let _ = writeln!(
            s,
            "/// Page groups: each page's faceplate PNGs, one per scale."
        );
        // Pages that render alike share a raster; two `include_bytes!` of one
        // file would embed it twice.
        let mut uses: Vec<(String, usize)> = Vec::new();
        for png in pages
            .iter()
            .flat_map(|g| &g.pages)
            .flatten()
            .map(|(_, p)| p)
        {
            let included = include(png);
            match uses.iter_mut().find(|(i, _)| *i == included) {
                Some((_, count)) => *count += 1,
                None if !matches!(png, PngRef::Url(_)) => uses.push((included, 1)),
                None => {}
            }
        }
        let mut shared: Vec<(String, String)> = Vec::new();
        for (included, _) in uses.into_iter().filter(|(_, count)| *count > 1) {
            let name = format!("SHARED_PAGE_PNG_{}", shared.len());
            let _ = writeln!(s, "static {name}: [u8; {included}.len()] = *{included};");
            shared.push((included, format!("&{name}")));
        }
        let page_png = |png: &PngRef| {
            let included = include(png);
            shared
                .iter()
                .find(|(i, _)| *i == included)
                .map_or(included, |(_, name)| name.clone())
        };
        let _ = writeln!(s, "#[allow(clippy::unreadable_literal)]");
        let _ = writeln!(
            s,
            "pub static PAGES: [{core}::PageGroup; {}] = [",
            pages.len()
        );
        for g in *pages {
            let r = g.region;
            let _ = writeln!(
                s,
                "    {core}::PageGroup::new({:?}, {core}::Rect::new({:?}, {:?}, {:?}, {:?}), &[",
                g.name, r.x, r.y, r.w, r.h
            );
            for page in &g.pages {
                let _ = writeln!(
                    s,
                    "        {core}::EmbeddedPngs::{}(SIZE, &[",
                    constructor(page)
                );
                for (scale, png) in page {
                    let _ = writeln!(s, "            ({scale:?}, {}),", page_png(png));
                }
                let _ = writeln!(s, "        ]),");
            }
            let _ = writeln!(s, "    ]),");
        }
        let _ = writeln!(s, "];");
    }
    s.push('\n');

    let _ = writeln!(s, "/// Pre-rendered faceplate PNGs, one per scale.");
    let _ = writeln!(
        s,
        "pub static FACEPLATE: {core}::EmbeddedPngs = {core}::EmbeddedPngs::{}(SIZE, &[",
        constructor(pngs)
    );
    for (scale, png) in *pngs {
        let _ = writeln!(s, "    ({scale:?}, {}),", include(png));
    }
    let _ = writeln!(s, "]);");
    s.push('\n');

    let _ = writeln!(
        s,
        "/// One field per control. Constructing this requires a value for every"
    );
    let _ = writeln!(
        s,
        "/// control in the SVG, so an unbound control is a compile error."
    );
    let _ = writeln!(s, "#[derive(Debug)]");
    let _ = writeln!(s, "pub struct Controls<B> {{");
    for c in *controls {
        let _ = writeln!(s, "    pub {}: B,", c.name);
    }
    let _ = writeln!(s, "}}");
    s.push('\n');
    let _ = writeln!(s, "impl<B> Controls<B> {{");
    let _ = writeln!(
        s,
        "    /// The values in [`ControlId`]({core}::ControlId) order."
    );
    let _ = writeln!(s, "    pub fn into_array(self) -> [B; {n}] {{");
    let fields: Vec<String> = controls
        .iter()
        .map(|c| format!("self.{}", c.name))
        .collect();
    let _ = writeln!(s, "        [{}]", fields.join(", "));
    let _ = writeln!(s, "    }}");
    let _ = writeln!(s, "}}");
    s
}

/// The `EmbeddedPngs` constructor for `pngs`: `fetched` for URLs.
fn constructor(pngs: &[(f32, PngRef)]) -> &'static str {
    if pngs.iter().any(|(_, p)| matches!(p, PngRef::Url(_))) {
        "fetched"
    } else {
        "new"
    }
}

/// An `include_bytes!` of `png`, or its URL.
fn include(png: &PngRef) -> String {
    match png {
        PngRef::Url(url) => format!("{url:?}"),
        PngRef::OutDir(f) => format!("include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{f}\"))"),
        PngRef::Absolute(p) => format!("include_bytes!({p:?})"),
    }
}
