/// An adjective and a noun from `rng`: "Vexatious Artichoke".
pub fn name(rng: &mut Rng) -> String {
    let adjective = ADJECTIVES[rng.below(ADJECTIVES.len())];
    let noun = NOUNS[rng.below(NOUNS.len())];
    format!("{adjective} {noun}")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Two lists, no duplicates, nothing but plain title-cased words
    ///.
    #[test]
    fn the_lists_are_plain_distinct_and_long_enough() {
        for list in [ADJECTIVES, NOUNS] {
            assert!(list.len() >= 150, "{} words", list.len());
            let mut seen = std::collections::HashSet::new();
            for w in list {
                assert!(seen.insert(w.to_lowercase()), "{w} twice");
                let mut chars = w.chars();
                assert!(chars.next().is_some_and(|c| c.is_ascii_uppercase()), "{w}");
                assert!(chars.all(|c| c.is_ascii_lowercase()), "{w}: one plain word");
            }
        }
    }
}
