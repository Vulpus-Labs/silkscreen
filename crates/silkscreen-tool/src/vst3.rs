//! `cargo silkscreen bundle <package> --vst3`: the plugin as a VST3, from
//! free-audio's clap-wrapper ([design/building-and-shipping.md]).
//!
//! The plugin package's library is built again as a `staticlib` and linked
//! into clap-wrapper's VST3 module, compiled with
//! `STATICALLY_LINKED_CLAP_ENTRY` so the wrapper takes the plugin's
//! `clap_entry` from the module itself. The `.vst3` is self-contained: it
//! neither needs nor looks for the `.clap`.
//!
//! clap-wrapper comes from git at [`CLAP_WRAPPER_TAG`], and fetches the
//! VST3 and CLAP SDKs at the versions that tag pins (VST3 SDK 3.8.0, MIT;
//! CLAP 1.2.10, MIT). Both are cached under `<target>/silkscreen-vst3/`,
//! with the `CMake` build, so later builds reuse them. Building needs `CMake`,
//! git and a C++ compiler; a missing one fails before anything is built,
//! naming what to install.
//!
//! `--validate` builds Steinberg's validator from the same SDK and runs it
//! on the `.vst3`.
//!
//! [design/building-and-shipping.md]: https://github.com/Vulpus-Labs/silkscreen/blob/main/design/building-and-shipping.md

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::files::{copy_tree, remove, write};
use crate::metadata::{Clap, Package, Workspace};

/// The clap-wrapper release VST3s are built with. It pins the SDKs.
pub const CLAP_WRAPPER_TAG: &str = "v0.18.0";
const CLAP_WRAPPER_URL: &str = "https://github.com/free-audio/clap-wrapper";

/// The `CMake` project that links the plugin into clap-wrapper's VST3.
const CMAKE_LISTS: &str = r#"# Generated by cargo silkscreen bundle --vst3: the plugin's static
# library inside clap-wrapper's VST3 module.
cmake_minimum_required(VERSION 3.21)
project(silkscreen_vst3 LANGUAGES C CXX)
if(APPLE)
    enable_language(OBJC OBJCXX)
endif()
set(CMAKE_CXX_STANDARD 17)
# Everything links into one shared module.
set(CMAKE_POSITION_INDEPENDENT_CODE ON)
# MSVC: the C runtime as a DLL, as Rust's own code uses it. clap-wrapper
# picks the static one unless this is set first, and the two can't mix.
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreadedDLL")
set(CLAP_WRAPPER_DOWNLOAD_DEPENDENCIES TRUE)
set(CLAP_WRAPPER_DONT_ADD_TARGETS TRUE)
add_subdirectory("${CLAP_WRAPPER_DIR}" clap-wrapper)

add_library(plugin_vst3 MODULE module.cpp)
target_add_vst3_wrapper(TARGET plugin_vst3
    OUTPUT_NAME "${VST3_NAME}"
    BUNDLE_IDENTIFIER "${VST3_BUNDLE_ID}"
    BUNDLE_VERSION "${VST3_VERSION}"
    WINDOWS_FOLDER_VST3 TRUE
    ASSET_OUTPUT_DIRECTORY "${VST3_OUT}")
# The plugin's clap_entry is linked in, not loaded from a .clap.
target_compile_definitions(clap-wrapper-shared-detail PRIVATE STATICALLY_LINKED_CLAP_ENTRY=1)

# What rustc says a static library of the plugin needs. A macOS
# framework is two words, which CMake would split; keep it one.
string(REGEX REPLACE "-framework ([A-Za-z0-9_]+)" "-Wl,-framework,\\1" native "${RUST_NATIVE_LIBS}")
separate_arguments(native NATIVE_COMMAND "${native}")
# MSVC: CMake links the C runtime itself; a /defaultlib flag here would be
# taken for a library file.
list(FILTER native EXCLUDE REGEX "^/defaultlib")
target_link_libraries(plugin_vst3 PRIVATE "${RUST_LIB}" ${native})

# Where clap-wrapper put the SDK, for the validator.
file(WRITE "${CMAKE_BINARY_DIR}/vst3sdk-root.txt" "${CMAKE_BINARY_DIR}/cpm/vst3sdk")
"#;

/// Build `p` as `<target>/bundled/<bundle>.vst3`, for `targets` (two make
/// a universal macOS binary; none builds for the host).
pub fn bundle(
    ws: &Workspace,
    p: &Package,
    clap: &Clap,
    debug: bool,
    targets: &[&str],
) -> Result<PathBuf, String> {
    check_tools()?;
    let work = ws.target_dir.join("silkscreen-vst3");
    let wrapper = fetch_wrapper(&work)?;

    let (libs, native) = if targets.is_empty() {
        let (lib, native) = static_lib(ws, p, debug, None)?;
        (vec![lib], native)
    } else {
        let mut libs = Vec::new();
        let mut native = String::new();
        for t in targets {
            let (lib, n) = static_lib(ws, p, debug, Some(t))?;
            libs.push(lib);
            native = n;
        }
        (libs, native)
    };
    let project = work.join(&p.name);
    std::fs::create_dir_all(&project).map_err(|e| format!("{}: {e}", project.display()))?;
    let lib = if let [lib] = libs.as_slice() {
        lib.clone()
    } else {
        let joined = project.join(lib_file_name(p)?);
        crate::bundle::lipo(&libs, &joined)?;
        joined
    };

    write(&project.join("CMakeLists.txt"), CMAKE_LISTS)?;
    write(
        &project.join("module.cpp"),
        "// The plugin is the Rust static library linked into this module.\n",
    )?;
    let build = project.join("build");
    let out = project.join("out");
    remove(&out)?;
    let mut configure = Command::new("cmake");
    configure
        .arg("-S")
        .arg(&project)
        .arg("-B")
        .arg(&build)
        .arg("-DCMAKE_BUILD_TYPE=Release")
        .arg(define("CLAP_WRAPPER_DIR", &wrapper))
        .arg(define("RUST_LIB", &lib))
        .arg(format!("-DRUST_NATIVE_LIBS={native}"))
        .arg(format!("-DVST3_NAME={}", clap.bundle))
        .arg(format!("-DVST3_BUNDLE_ID={}.vst3", clap.id))
        .arg(format!("-DVST3_VERSION={}", p.version))
        .arg(define("VST3_OUT", &out));
    if cfg!(target_os = "macos") {
        let archs: Vec<&str> = if targets.is_empty() {
            vec![std::env::consts::ARCH]
        } else {
            targets
                .iter()
                .map(|t| t.split('-').next().unwrap_or(t))
                .collect()
        };
        let archs = archs
            .iter()
            .map(|a| if *a == "aarch64" { "arm64" } else { a })
            .collect::<Vec<_>>()
            .join(";");
        configure
            .arg(format!("-DCMAKE_OSX_ARCHITECTURES={archs}"))
            .arg("-DCMAKE_OSX_DEPLOYMENT_TARGET=11.0");
    }
    cmake(&mut configure, "configuring the VST3 wrapper")?;
    cmake(
        Command::new("cmake").arg("--build").arg(&build).args([
            "--config",
            "Release",
            "--parallel",
        ]),
        "building the VST3 wrapper",
    )?;

    let made = out.join(format!("{}.vst3", clap.bundle));
    if !made.exists() {
        return Err(format!(
            "clap-wrapper built no {}; the CMake output above says why",
            made.display()
        ));
    }
    let dest = ws
        .target_dir
        .join("bundled")
        .join(format!("{}.vst3", clap.bundle));
    remove(&dest)?;
    copy_tree(&made, &dest, &|_| true)?;
    Ok(dest)
}

/// Build Steinberg's validator from the SDK the last [`bundle`] of `p`
/// used, and run it on `vst3`.
pub fn validate(ws: &Workspace, p: &Package, vst3: &Path) -> Result<(), String> {
    let project = ws.target_dir.join("silkscreen-vst3").join(&p.name);
    let root_file = project.join("build").join("vst3sdk-root.txt");
    let sdk = std::fs::read_to_string(&root_file)
        .map_err(|e| format!("{}: {e} (build the VST3 first)", root_file.display()))?;
    let build = project.join("validator");
    let mut configure = Command::new("cmake");
    configure
        .arg("-S")
        .arg(sdk.trim())
        .arg("-B")
        .arg(&build)
        .args([
            "-DCMAKE_BUILD_TYPE=Release",
            "-DSMTG_ENABLE_VSTGUI_SUPPORT=OFF",
            "-DSMTG_ENABLE_VST3_PLUGIN_EXAMPLES=OFF",
            "-DSMTG_ENABLE_VST3_HOSTING_EXAMPLES=ON",
            "-DSMTG_RUN_VST_VALIDATOR=OFF",
        ]);
    if cfg!(target_os = "macos") && !xcode_installed() {
        // The SDK's CMake asks xcodebuild for Xcode's version, and refuses
        // to go on without one; the Command Line Tools build it as well.
        configure
            .env("XCODE_VERSION", "16.0")
            .arg("-DXCODE_VERSION=16.0");
    }
    cmake(&mut configure, "configuring the VST3 validator").map_err(|e| {
        if cfg!(target_os = "linux") {
            // The SDK configures its editor host beside the validator.
            format!("{e}. On Linux the SDK's hosting examples also need GTK 3 and gtkmm 3 (`sudo apt install libgtk-3-dev libgtkmm-3.0-dev`)")
        } else {
            e
        }
    })?;
    cmake(
        Command::new("cmake").arg("--build").arg(&build).args([
            "--config",
            "Release",
            "--target",
            "validator",
            "--parallel",
        ]),
        "building the VST3 validator",
    )?;
    let exe = if cfg!(windows) {
        "validator.exe"
    } else {
        "validator"
    };
    let validator = build.join("bin").join("Release").join(exe);
    let status = Command::new(&validator)
        .arg(vst3)
        .status()
        .map_err(|e| format!("running {}: {e}", validator.display()))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("the VST3 validator failed {}", vst3.display()))
    }
}

/// The user's VST3 folder on this platform.
pub fn install_dir() -> Result<PathBuf, String> {
    let home = std::env::var_os("HOME").map(PathBuf::from);
    match std::env::consts::OS {
        "macos" => Ok(home
            .ok_or("HOME not set")?
            .join("Library/Audio/Plug-Ins/VST3")),
        "linux" => Ok(home.ok_or("HOME not set")?.join(".vst3")),
        "windows" => std::env::var_os("LOCALAPPDATA")
            .map(|d| PathBuf::from(d).join("Programs/Common/VST3"))
            .ok_or_else(|| "LOCALAPPDATA not set".into()),
        os => Err(format!("no VST3 install folder known for {os}")),
    }
}

/// Fail early, naming what to install, if a build tool is missing. `CMake`
/// itself reports a missing C++ compiler; [`cmake`] adds what to install.
fn check_tools() -> Result<(), String> {
    for (tool, install) in [
        (
            "cmake",
            "CMake 3.21 or later (https://cmake.org/download/, or `brew install cmake`)",
        ),
        ("git", "git"),
    ] {
        let found = Command::new(tool)
            .arg("--version")
            .output()
            .is_ok_and(|o| o.status.success());
        if !found {
            return Err(format!("--vst3 needs {tool}: install {install}"));
        }
    }
    Ok(())
}

/// clap-wrapper at [`CLAP_WRAPPER_TAG`], cloned once into `work`.
fn fetch_wrapper(work: &Path) -> Result<PathBuf, String> {
    let dir = work.join(format!("clap-wrapper-{CLAP_WRAPPER_TAG}"));
    if dir.join("CMakeLists.txt").exists() {
        return Ok(dir);
    }
    std::fs::create_dir_all(work).map_err(|e| format!("{}: {e}", work.display()))?;
    // Clone beside it and rename, so an interrupted clone isn't taken for
    // a finished one.
    let partial = work.join(format!("clap-wrapper-{CLAP_WRAPPER_TAG}.partial"));
    remove(&partial)?;
    // A checkout without its CMakeLists.txt is incomplete: a cache may
    // restore part of one. Start again.
    remove(&dir)?;
    crate::run_command(
        Command::new("git")
            .args([
                "clone",
                "--quiet",
                "--depth",
                "1",
                "--branch",
                CLAP_WRAPPER_TAG,
            ])
            .arg(CLAP_WRAPPER_URL)
            .arg(&partial),
    )?;
    std::fs::rename(&partial, &dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    Ok(dir)
}

/// Build `p`'s library as a `staticlib`, for `target` or the host: its path
/// and the native libraries rustc says it needs.
fn static_lib(
    ws: &Workspace,
    p: &Package,
    debug: bool,
    target: Option<&str>,
) -> Result<(PathBuf, String), String> {
    let mut cargo = crate::cargo();
    cargo.current_dir(&ws.root).args([
        "rustc",
        "--package",
        &p.name,
        "--lib",
        "--crate-type",
        "staticlib",
        "--message-format",
        "json",
    ]);
    if !debug {
        cargo.arg("--release");
    }
    if let Some(t) = target {
        cargo.args(["--target", t]);
    }
    cargo.args(["--", "--print", "native-static-libs"]);
    let out = cargo
        .stderr(std::process::Stdio::inherit())
        .output()
        .map_err(|e| format!("running cargo: {e}"))?;
    let messages = String::from_utf8_lossy(&out.stdout);
    if !out.status.success() {
        for text in rendered(&messages) {
            eprint!("{text}");
        }
        return Err(format!("building {} as a static library failed", p.name));
    }
    // JSON keeps rustc's note where we can read it; show the rest as cargo
    // would have.
    for text in rendered(&messages) {
        eprint!("{text}");
    }
    let native = native_static_libs(&messages).ok_or_else(|| {
        format!(
            "rustc didn't say which native libraries {} needs; run `cargo clean -p {}` and try again",
            p.name, p.name
        )
    })?;

    let profile = if debug { "debug" } else { "release" };
    let mut dir = ws.target_dir.clone();
    if let Some(t) = target {
        dir.push(t);
    }
    dir.push(profile);
    Ok((dir.join(lib_file_name(p)?), native))
}

/// The static library's file name: `lib<name>.a`, or `<name>.lib` on
/// Windows.
fn lib_file_name(p: &Package) -> Result<String, String> {
    let lib = p.lib.as_deref().ok_or_else(|| {
        format!(
            "{} has no library target to wrap: add a [lib] with crate-type = [\"cdylib\", \"rlib\"]",
            p.name
        )
    })?;
    Ok(if cfg!(windows) {
        format!("{lib}.lib")
    } else {
        format!("lib{lib}.a")
    })
}

/// Each compiler message's text as rustc renders it, but for the
/// native-static-libs notes.
fn rendered(messages: &str) -> Vec<String> {
    messages
        .lines()
        .filter_map(|line| {
            let v: serde_json::Value = serde_json::from_str(line).ok()?;
            let m = v.get("message")?;
            let text = m.get("message")?.as_str()?;
            if text.starts_with("native-static-libs")
                || text.starts_with("link against the following native artifacts")
            {
                return None;
            }
            Some(m.get("rendered")?.as_str()?.to_owned())
        })
        .collect()
}

/// The libraries in rustc's `native-static-libs` note, from cargo's JSON
/// messages (cargo replays them when the build was already fresh).
fn native_static_libs(messages: &str) -> Option<String> {
    const NOTE: &str = "native-static-libs: ";
    messages.lines().find_map(|line| {
        let v: serde_json::Value = serde_json::from_str(line).ok()?;
        let text = v.get("message")?.get("message")?.as_str()?;
        text.strip_prefix(NOTE).map(|libs| libs.trim().to_owned())
    })
}

fn define(name: &str, path: &Path) -> String {
    format!("-D{name}={}", path.display())
}

fn xcode_installed() -> bool {
    Command::new("xcodebuild")
        .arg("-version")
        .output()
        .is_ok_and(|o| o.status.success())
}

/// Run a `CMake` step; on failure, say what it was and, if it may be a
/// missing compiler, what to install.
fn cmake(cmd: &mut Command, what: &str) -> Result<(), String> {
    let status = cmd
        .status()
        .map_err(|e| format!("{what}: running cmake: {e}"))?;
    if status.success() {
        return Ok(());
    }
    let compiler = match std::env::consts::OS {
        "macos" => "the Xcode Command Line Tools (`xcode-select --install`)",
        "windows" => "Visual Studio or its Build Tools, with \"Desktop development with C++\"",
        _ => "a C and C++ compiler (`sudo apt install build-essential`)",
    };
    Err(format!(
        "{what} failed (see the output above). If CMake found no compiler, install {compiler}"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_native_static_libs_from_cargo_messages() {
        let messages = concat!(
            r#"{"reason":"compiler-artifact","target":{"name":"x"}}"#,
            "\n",
            r#"{"reason":"compiler-message","message":{"message":"native-static-libs: -framework AppKit -lSystem -lc","level":"note"}}"#,
            "\n",
        );
        assert_eq!(
            native_static_libs(messages).as_deref(),
            Some("-framework AppKit -lSystem -lc")
        );
        assert_eq!(native_static_libs("{}\nnot json\n"), None);
    }

    #[test]
    fn the_cmake_project_links_the_entry_statically() {
        assert!(CMAKE_LISTS.contains("STATICALLY_LINKED_CLAP_ENTRY=1"));
        assert!(CMAKE_LISTS.contains("WINDOWS_FOLDER_VST3 TRUE"));
        assert!(CMAKE_LISTS.contains("CMAKE_POSITION_INDEPENDENT_CODE ON"));
        assert!(CMAKE_LISTS.contains("\"MultiThreadedDLL\""));
    }
}
